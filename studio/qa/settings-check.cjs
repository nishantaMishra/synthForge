const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const path=require('node:path');

(async()=>{
  const browser=await chromium.launch({headless:true,executablePath:'/home/nishant/.cache/ms-playwright/chromium-1208/chrome-linux64/chrome',args:['--no-sandbox']});
  const page=await browser.newPage({viewport:{width:1536,height:1120}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  let socket,submitted,requests=0;
  await page.routeWebSocket('**/comfy/ws**',ws=>{socket=ws;});
  await page.route('**/api/run',async route=>{
    requests++;submitted=route.request().postDataJSON();
    await route.fulfill({json:{prompt_id:submitted.prompt_id,number:0,node_errors:{}}});
    socket.send(JSON.stringify({type:'execution_start',data:{prompt_id:submitted.prompt_id}}));
    socket.send(JSON.stringify({type:'executing',data:{prompt_id:submitted.prompt_id,node:'595'}}));
  });
  await page.goto('http://127.0.0.1:8190');
  await page.waitForFunction(()=>document.getElementById('connectionText').textContent==='Engine connected');
  assert.equal(await page.locator('#settings').isVisible(),true);
  assert.equal(await page.locator('#engineBanner').isVisible(),true);
  await page.locator('#adaptiveLevel').fill('3');
  await page.locator('#denoiseMin').fill('0.03');
  await page.locator('#denoiseMax').fill('0.07');
  await page.getByRole('button',{name:'Minimal',exact:false}).click();
  assert.equal(await page.locator('#settings').isVisible(),true);
  await page.reload();
  await page.waitForFunction(()=>document.getElementById('connectionText').textContent==='Engine connected');
  assert.equal(await page.locator('#adaptiveLevel').inputValue(),'3');
  assert.equal(await page.locator('#denoiseMin').inputValue(),'0.03');
  assert.equal(await page.locator('#denoiseMax').inputValue(),'0.07');
  await page.locator('#fileInput').setInputFiles(path.resolve(__dirname,'../../ComfyUI/input/example.png'));
  await page.waitForFunction(()=>!document.getElementById('runButton').disabled);
  assert.match(await page.locator('#runButton').textContent(),/CPU \(slow\)/);
  await page.locator('#runButton').click();
  await page.waitForFunction(()=>document.getElementById('toolTitle').textContent==='Choose reconstruction strength');
  assert.deepEqual(submitted.settings,{adaptive_level:3,denoise_min:0.03,denoise_max:0.07});
  assert.equal(await page.locator('#adaptiveLevel').isDisabled(),true);
  assert.match(await page.locator('#toolDetailsText').textContent(),/"adaptive_level": 3/);
  assert.match(await page.locator('#runDetail').textContent(),/CPU/);
  socket.send(JSON.stringify({type:'execution_interrupted',data:{prompt_id:submitted.prompt_id}}));
  await page.waitForFunction(()=>document.getElementById('runStatus').textContent==='Run stopped');
  assert.equal(await page.locator('#adaptiveLevel').isEnabled(),true);
  await page.locator('#denoiseMin').fill('0.2');await page.locator('#runButton').click();
  assert.match(await page.locator('#notice').textContent(),/minimum/);assert.equal(requests,1);
  await page.locator('#denoiseMin').fill('0.03');
  await page.screenshot({path:path.resolve(__dirname,'artifacts/settings-and-cpu.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.route('**/api/health',route=>route.fulfill({json:{ready:true,devices:[{type:'cuda',name:'cuda:0 NVIDIA GPU'}],nodes:36}}));
  await page.reload();
  await page.waitForFunction(()=>document.getElementById('connectionText').textContent==='Engine connected');
  assert.equal(await page.locator('#engineBanner').isVisible(),false);
  assert.doesNotMatch(await page.locator('#runButton').textContent(),/CPU/);
  assert.deepEqual(errors,[]);
  await browser.close();
  console.log('PASS: visible settings in both views, persistence, exact run payload, settings lock, input validation, CPU warning/label, GPU indicator, mobile. No inference job was queued.');
})().catch(error=>{console.error(error);process.exit(1);});
